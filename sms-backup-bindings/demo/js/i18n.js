  // Align with App UiLocales.options (+ Follow system as empty tag)
  const localeLabels = [
    { id: "", native: null }, // label via t("settings_language_system")
    { id: "en", native: "English" },
    { id: "zh-CN", native: "简体中文" },
    { id: "zh-TW", native: "繁體中文" },
    { id: "ja", native: "日本語" },
    { id: "ko", native: "한국어" },
    { id: "de", native: "Deutsch" },
    { id: "fr", native: "Français" },
    { id: "es", native: "Español" },
    { id: "pt", native: "Português" },
    { id: "vi", native: "Tiếng Việt" },
  ];

  const PACK_IDS = ["en", "zh-CN", "zh-TW", "ja", "ko", "de", "fr", "es", "pt", "vi"];
  const STORAGE_KEY = "demo.locale";

  let preference = ""; // "" = follow system (App UiLocales.SYSTEM)
  let locale = "en"; // effective pack id

  function normalizeTag(tag) {
    tag = String(tag || "").replace(/_/g, "-").trim();
    if (!tag) return "";
    const parts = tag.split("-").filter(Boolean);
    if (!parts.length) return "";
    parts[0] = parts[0].toLowerCase();
    for (let i = 1; i < parts.length; i++) {
      const p = parts[i];
      if (p.length === 4) {
        parts[i] = p.charAt(0).toUpperCase() + p.slice(1).toLowerCase();
      } else if (p.length === 2 || p.length === 3) {
        parts[i] = p.toUpperCase();
      } else {
        parts[i] = p.toLowerCase();
      }
    }
    return parts.join("-");
  }

  function resolveFromNavigator() {
    const list = [];
    if (typeof navigator !== "undefined") {
      if (navigator.languages && navigator.languages.length) {
        for (let i = 0; i < navigator.languages.length; i++) list.push(navigator.languages[i]);
      }
      if (navigator.language) list.push(navigator.language);
    }
    const supported = Object.create(null);
    PACK_IDS.forEach((id) => { supported[id] = true; });

    // Walk browser prefs in order: exact/near-exact, then language-only per candidate
    for (let i = 0; i < list.length; i++) {
      const n = normalizeTag(list[i]);
      if (!n) continue;
      if (supported[n]) return n;
      const parts = n.split("-");
      // zh-Hans-CN → zh-CN
      if (parts.length >= 3) {
        const langRegion = parts[0] + "-" + parts[parts.length - 1];
        if (supported[langRegion]) return langRegion;
      }
      if (parts.length >= 2) {
        const two = parts[0] + "-" + parts[1];
        if (supported[two]) return two;
      }
      const lang = parts[0];
      const rest = parts.slice(1);
      const script = rest.find((p) => p.length === 4) || "";
      const region = rest.find((p) => p.length === 2 || p.length === 3) || "";
      if (lang === "zh") {
        if (script === "Hant" || region === "TW" || region === "HK" || region === "MO") return "zh-TW";
        return "zh-CN";
      }
      if (lang === "pt" && supported.pt) return "pt";
      if (supported[lang]) return lang;
    }
    return "en";
  }

  function readStoredPreference() {
    try {
      if (typeof sessionStorage === "undefined") return null;
      return sessionStorage.getItem(STORAGE_KEY);
    } catch (e) {
      return null;
    }
  }

  function writeStoredPreference(pref) {
    try {
      if (typeof sessionStorage === "undefined") return;
      sessionStorage.setItem(STORAGE_KEY, pref);
    } catch (e) { /* ignore */ }
  }

  function applyPreference(pref) {
    if (pref === "" || pref === "system" || pref == null) {
      preference = "";
      locale = resolveFromNavigator();
      if (!packs[locale]) locale = "en";
    } else if (packs[pref]) {
      preference = pref;
      locale = pref;
    } else {
      preference = "";
      locale = resolveFromNavigator();
      if (!packs[locale]) locale = "en";
    }
    return locale;
  }

  function initLocale() {
    const saved = readStoredPreference();
    // missing → follow browser (do not write until user picks)
    if (saved === null) {
      preference = "";
      locale = resolveFromNavigator();
      if (!packs[locale]) locale = "en";
      return locale;
    }
    return applyPreference(saved);
  }

  function t(key, vars) {
    const pack = packs[locale] || packs.en;
    let s = pack[key] != null ? pack[key] : packs.en[key] || key;
    if (vars) {
      Object.keys(vars).forEach((k) => {
        s = s.replace(new RegExp("\\{" + k + "\\}", "g"), String(vars[k]));
      });
    }
    return s;
  }

  function setLocale(id) {
    if (id === "system" || id === "" || id == null) {
      preference = "";
      locale = resolveFromNavigator();
      if (!packs[locale]) locale = "en";
      writeStoredPreference("");
    } else if (packs[id]) {
      preference = id;
      locale = id;
      writeStoredPreference(id);
    } else {
      preference = "";
      locale = "en";
      writeStoredPreference("");
    }
    return locale;
  }

  function getLocale() {
    return locale;
  }

  /** Preference tag: "" = Follow system; else a pack id. */
  function getLocalePreference() {
    return preference;
  }

